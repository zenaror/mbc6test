#!/usr/bin/env python3
"""Generate src/font_data.asm: an original, hand-authored 5x7 bitmap
font rendered as Game Boy 2bpp tile data (8x8 cells, low bitplane =
the glyph, high bitplane = 0, so a single-palette color 1 is the
foreground). No external font asset is used — every glyph's pixels
are defined below.

Character order matches the ASCII range $20 ('.' space) through the
last defined glyph, so tile index = ord(char) - 0x20. Unmapped
characters in that range fall back to a solid block placeholder so a
typo shows up as a visible glyph instead of vanishing.
"""
import sys
from pathlib import Path

# Each glyph: 7 rows (top to bottom) of a 5-wide bitmap, MSB-aligned
# into an 8-wide tile row (bits 7..3 used, bits 2..0 always 0 — that
# gives a 3px gap to the next character when printed edge to edge).
