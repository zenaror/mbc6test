FIRST_CODE = 0x20
LAST_CODE = 0x5A  # 'Z'

FALLBACK = ["11111"] * 7


def glyph_rows(ch: str):
    return GLYPHS.get(ch, FALLBACK)


def encode_tile(rows) -> bytes:
    out = bytearray()
    for row in rows:
        bits = row + "000"  # pad 5 -> 8 wide
        plane0 = int(bits, 2)
        out.append(plane0)
        out.append(0x00)
    # Pad 7 rows -> 8 tile rows.
    out += b"\x00\x00"
    return bytes(out)


def main() -> None:
    lines = [
        "; Generated by tools/gen_font.py — do not hand-edit.",
        "; Original 5x7 bitmap font, 8x8 GB 2bpp tiles, one glyph per",
        "; tile. Tile index = ASCII code - $20. See gen_font.py for the",
        "; source bitmaps (no external font asset is used).",
        "",
        "; Lives in fixed ROM (not ROMX) so the UI can load it with a",
        "; plain memcpy, with no MBC6 bank switch involved.",
        "SECTION \"Font Data\", ROM0",
        "",
        "FontTiles::",
    ]
    for code in range(FIRST_CODE, LAST_CODE + 1):
        ch = chr(code)
        tile = encode_tile(glyph_rows(ch))
        comment = ch if ch.strip() else "SPACE"
        lines.append(f"    db {', '.join(f'${b:02X}' for b in tile)} ; ${code:02X} '{comment}'")
    lines.append("FontTilesEnd::")
    lines.append("")

    out_path = Path(__file__).parent.parent / "src" / "font_data.asm"
    out_path.write_text("\n".join(lines))
    print(f"wrote {out_path} ({LAST_CODE - FIRST_CODE + 1} glyphs)")


if __name__ == "__main__":
    main()
